// ---- Install: precache everything --------------------------
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // Precache from the NETWORK, never the browser's HTTP cache. Image URLs are
    // reused across content swaps (img/<id>.webp is overwritten when a photo
    // changes), so a plain fetch can hand back bytes the browser is still
    // holding under an earlier `immutable` response — which is exactly how a
    // real-photo deploy left old placeholders cached. `cache: 'reload'` bypasses
    // the HTTP cache so the worker always stores the current bytes.
    // addAll stays atomic-ish: if any asset 404s the install fails, which is
    // what we want — a half-cached app is worse than a failed update.
    await cache.addAll(PRECACHE.map(url => new Request(url, { cache: 'reload' })));
    await self.skipWaiting();
  })());
});

// ---- Activate: purge old versions --------------------------
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(
      // Also the old v2 cache from the root-scoped worker: the root worker
      // keeps it as Osa's offline copy until this worker has installed.
      keys.filter(k => (k.startsWith('osa-bingo-v3-') && k !== CACHE) || k.startsWith('osa-bingo-v2-'))
          .map(k => caches.delete(k))
    );
    await self.clients.claim();
  })());
});

// ---- Fetch strategies --------------------------------------
async function staleWhileRevalidate(request, fallbackKey) {
  const cache = await caches.open(CACHE);
  const cached = (await cache.match(request)) ||
                 (fallbackKey ? await cache.match(fallbackKey) : undefined);
  const network = fetch(request)
    .then(res => { if (res && res.ok) cache.put(request, res.clone()); return res; })
    .catch(() => undefined);
  return cached || (await network) || (await cache.match('index.html'));
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  try {
    const res = await fetch(request);
    if (res && res.ok) cache.put(request, res.clone());
    return res;
  } catch (err) {
    return cached || Response.error();
  }
}

self.addEventListener('fetch', event => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;   // don't touch cross-origin

  // This worker's scope is /osa/, so the browser only sends it Osa's own
  // pages and the requests those pages make. Plant bingo and the hub have
  // their own workers and are never routed here.

  // The HTML shell: fresh when possible, cached when not.
  if (request.mode === 'navigate') {
    event.respondWith(staleWhileRevalidate(request, 'index.html'));
    return;
  }
  // Species data can change without a version bump: keep it fresh.
  if (url.pathname.endsWith('/species.json') || url.pathname.endsWith('species.json')) {
    event.respondWith(staleWhileRevalidate(request));
    return;
  }
  // Everything else (css, js, fonts, images, icons, manifest).
  event.respondWith(cacheFirst(request));
});
